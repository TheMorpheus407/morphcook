String translate(String lang, String key, [Map<String, Object?> args = const {}]) {
  var s = uiStrings[lang]?[key] ?? uiStrings['en']![key] ?? key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

/// Lightweight accessor bound to the current profile language.
class Tr {
  const Tr(this.lang);
  final String lang;
  String call(String key, [Map<String, Object?> args = const {}]) => translate(lang, key, args);
}

extension TrContext on BuildContext {
  /// Listens to language changes.
  Tr get tr => Tr(select<ProfileController, String>((p) => p.lang));

  /// Non-listening variant for callbacks.
  Tr get trRead => Tr(read<ProfileController>().lang);

  String get lang => select<ProfileController, String>((p) => p.lang);
}
