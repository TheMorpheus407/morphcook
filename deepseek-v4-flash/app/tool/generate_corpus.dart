  final allIds = <String>{};
  void collectIds(List<Map<String, dynamic>> nodes) {
    for (final n in nodes) {
      allIds.add(n['id'] as String);
      collectIds((n['children'] as List).cast<Map<String, dynamic>>());
    }
  }

  final categories =
      ((File('${out.path}/ingredients.json')
              .readAsStringSync()
              .letJsonDecode())['categories'] as List)
          .cast<Map<String, dynamic>>();
  collectIds(categories);

  final unknown = <String>[];
  for (final r in recipes) {
    for (final ing in r.ingredients) {
      if (!allIds.contains(ing.id)) unknown.add('${r.id}:${ing.id}');
    }
  }
  if (unknown.isNotEmpty) {
    throw StateError('unknown ingredient ids: $unknown');
  }

  final missingDish = recipes.where((r) => !dishes.any((d) => d['id'] == r.dish));
  if (missingDish.isNotEmpty) {
    throw StateError('recipes with unknown dishes: '
        '${missingDish.map((r) => r.id).toList()}');
  }

  // stats
  final sizes = <String, int>{};
  for (final f in out.listSync().whereType<File>()) {
    sizes[f.path.split('/').last] = f.lengthSync();
  }
  print('recipes: ${recipes.length} | dishes: ${dishes.length}');
  print('guides: ${guides.length} | faqs: ${faqs.length}');
  print('ingredients: ${allIds.length}');
  print(sizes);
  print('ALL CHECKS PASSED');
}

