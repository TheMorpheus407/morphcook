Map<String, dynamic> _recipeJson(RecipeData r) {
  // --- flag-verifier: derive flags from ingredients, then verify manual flags.
  final derived = <String>{};
  for (final ing in r.ingredients) {
    derived.addAll(flagsOf[ing.id] ?? const <String>{});
  }
  final allFlags = derived.union(r.extraFlags);

  final dietConsistency = <String, Set<String>>{
    'vegan': {
      'pork', 'beef', 'lamb', 'poultry', 'fish', 'shellfish', 'molluscs',
      'egg', 'dairy', 'honey',
    },
    'vegetarian': {
      'pork', 'beef', 'lamb', 'poultry', 'fish', 'shellfish', 'molluscs',
    },
    'pescatarian': {'pork', 'beef', 'lamb', 'poultry'},
    'halal': {'pork', 'alcohol'},
    'kosher': {'pork', 'shellfish'},
    'gluten-free': {'gluten'},
    'low-fodmap': {'high-fodmap'},
    'sugar-free': {'added-sugar'},
    'lactose-free': {
      'dairy', 'cow-milk', 'cheese', 'cream', 'yogurt', 'sour-cream',
    },
    'keto': {},
    'classic': {},
  };
  final conflicts = allFlags.intersection(dietConsistency[r.diet] ?? const {});
  if (conflicts.isNotEmpty) {
    throw StateError(
        '${r.id}: diet ${r.diet} conflicts with flags $conflicts (ingredients: '
        '${r.ingredients.map((i) => i.id).toList()})');
  }

  final calories = r.calories;
  final time = r.minutes;
  final attributes = <String>[
    r.effort,
    time <= 15 ? '≤15' : (time <= 30 ? '≤30' : (time <= 60 ? '≤60' : '>60')),
    calories <= 400
        ? '≤400'
        : (calories <= 600 ? '≤600' : (calories <= 800 ? '≤800' : '>800')),
    ...r.techniques,
  ];

  final dish = dishes.firstWhere((d) => d['id'] == r.dish,
      orElse: () => throw StateError('${r.id}: unknown dish ${r.dish}'));
  final secondaries = List<String>.from(dish['secondary_partitions']);
  if (secondaries.contains('cuisine-italian') ||
      secondaries.contains('cuisine-asian') ||
      secondaries.contains('cuisine-middle-eastern')) {
    attributes.addAll(secondaries.where((s) => s.startsWith('cuisine-')));
  }
  final unique = <String>{};
  attributes.retainWhere((a) => unique.add(a));

  return {
    'id': r.id,
    'dish_id': r.dish,
    'title': {'en': r.titleEn, 'de': r.titleDe},
    'summary': {'en': r.summaryEn, 'de': r.summaryDe},
    'diet': r.diet,
    'contains': allFlags.toList()..sort(),
    'attributes': attributes,
    'time_minutes': time,
    'calories_per_serving': calories,
    'protein_g': r.protein,
    'carbs_g': r.carbs,
    'fat_g': r.fat,
    'servings': r.servings,
    'meal_types': r.mealTypes,
    'tags': r.tags,
    'ingredients': [
      for (final ing in r.ingredients)
        {
          'id': ing.id,
          'amount': ing.amount,
          'unit': ing.unit,
          if (ing.note != null) 'note': ing.note,
        }
    ],
    'steps': [
      for (final s in r.steps)
        {
          'text': {'en': s.en, 'de': s.de},
          if (s.timer > 0) 'timer_seconds': s.timer,
        }
    ],
    if (r.noteEn.isNotEmpty)
      'kitchen_notes': {'en': r.noteEn, 'de': r.noteDe},
    'reviewed': true,
  };
}

Map<String, dynamic> _ingredientNode(String id) {
  if (!labels.containsKey(id)) {
    throw StateError('no label for ingredient node: $id');
  }
  return {
    'id': id,
    'label': {'en': labels[id]![0], 'de': labels[id]![1]},
    'children': [
      for (final c in parents[id] ?? const <String>[]) _ingredientNode(c),
    ],
  };
}

void main() {
  _all();
  if (recipes.length != recipes.map((r) => r.id).toSet().length) {
    throw StateError('duplicate recipe ids');
  }

  // dishes with their variant ids
  final dishVariants = <String, List<String>>{};
  for (final r in recipes) {
    dishVariants.putIfAbsent(r.dish, () => []).add(r.id);
  }
  final dishJson = <Map<String, dynamic>>[];
  for (final d in dishes) {
    final id = d['id'] as String;
    final variants = dishVariants[id]!;
    final dish = Map<String, dynamic>.from(d);
    dish['variant_ids'] = variants;
    // fill german hero/caption
    dish['hero_text'] = {
      'en': d['hero_text']['en'],
      'de': _germanHero(id),
    };
    dish['cap_caption'] = {
      'en': d['cap_caption']['en'],
      'de': _germanCap(id),
    };
    dishJson.add(dish);
  }

  // partition manifest
  final coreDishes = dishJson.where((d) => d['frequency_tier'] == 1).toList();
  final extendedDishes =
      dishJson.where((d) => d['frequency_tier'] == 2).toList();
  final coreIds = coreDishes.map((d) => d['id']).toSet();
  final extendedIds = extendedDishes.map((d) => d['id']).toSet();

  final cuisineMap = <String, List<String>>{};
  for (final d in dishJson) {
    for (final c in d['secondary_partitions'] as List) {
      if (c is String && c.startsWith('cuisine-')) {
        cuisineMap.putIfAbsent(c, () => []).addAll((d['variant_ids'] as List).cast<String>());
      }
    }
  }

  final cuisineTags = <String, String>{
    'cuisine-italian': 'italian',
    'cuisine-asian': 'asian',
    'cuisine-middle-eastern': 'middle-eastern',
  };

  final manifest = {
    'schema_version': 1,
    'updated_at': '2026-08-05',
    'default_strategy': 'lazy',
    'loading': {
      'strategy': 'launch+on-demand',
      'preload': ['core'],
      'on_demand': ['extended', 'cuisine-*'],
    },
    'partitions': [
      {
        'id': 'core',
        'file': 'core-recipes.json',
        'strategy': 'launch',
        'recipe_ids': [
          for (final r in recipes)
            if (coreIds.contains(r.dish)) r.id,
        ],
        'dish_ids': coreDishes.map((d) => d['id']).toList(),
      },
      {
        'id': 'extended',
        'file': 'extended-recipes.json',
        'strategy': 'lazy',
        'recipe_ids': [
          for (final r in recipes)
            if (extendedIds.contains(r.dish)) r.id,
        ],
        'dish_ids': extendedDishes.map((d) => d['id']).toList(),
      },
      for (final entry in cuisineMap.entries)
        {
          'id': entry.key,
          'file': '${entry.key}.json',
          'strategy': 'lazy',
          'recipe_ids': entry.value,
          'dish_ids': [
            for (final d in dishJson)
              if (d['secondary_partitions'].contains(entry.key)) d['id'],
