          'cuisine_tag': cuisineTags[entry.key],
        },
    ],
    'cross_references': {
      for (final c in cuisineMap.keys)
        c: ['core', 'extended'],
    },
  };

  final out = Directory('assets/data')..createSync(recursive: true);

  Map<String, dynamic> recipeById(String id) =>
      _recipeJson(recipes.firstWhere((r) => r.id == id));

  final coreJson = {
    'partition': 'core',
    'recipes': [
      for (final r in recipes)
        if (coreIds.contains(r.dish)) recipeById(r.id),
    ],
  };
  final extendedJson = {
    'partition': 'extended',
    'recipes': [
      for (final r in recipes)
        if (extendedIds.contains(r.dish)) recipeById(r.id),
    ],
  };

  for (final entry in cuisineMap.entries) {
    final json = {
      'partition': entry.key,
      'cuisine_tag': cuisineTags[entry.key],
      'recipes': [for (final id in entry.value) recipeById(id)],
    };
