def build():
    seen = set()
    nodes = []
    for (nid, parent, en, de, aisle, unit, flags) in T:
        if nid in seen:
            raise ValueError(f'duplicate ingredient id: {nid}')
        seen.add(nid)
        nodes.append({
            "id": nid,
            "parent": parent,
            "label": {"en": en, "de": de},
            "aisle": aisle,
            "unit_type": unit,
            "flags": flags,
        })
    for node in nodes:
        if node["parent"] is not None and node["parent"] not in seen:
            raise ValueError(f'unknown parent {node["parent"]} on {node["id"]}')
    return {"schema_version": 1, "nodes": nodes}


